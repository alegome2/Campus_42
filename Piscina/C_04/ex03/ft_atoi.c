#include <stdio.h>

int	ft_atoi(char *str)
{
	int	i;
	int	signo;
	int	number;

	i = 0;
	signo = 1;
	number= 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == ' ')
		i++;
	while (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			signo = signo * -1;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		number = (number * 10) + (str[i] - '0');
		i++;
	}
	return (number * signo);
}

int	main(void)
{
	char	str[30] = "  ---++-+----1234as4556";
	printf("%i\n", ft_atoi(str));
	return(0);
}
